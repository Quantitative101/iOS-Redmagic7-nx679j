#!/usr/bin/env python3
"""Embed userland files in the kernel: write rm_blob.h for bsd/dev/rm_blob.c.

usage: gen-blob.py OUT.h DEST_PATH=LOCAL_FILE [...]
Each file becomes a byte array the kernel writes to DEST_PATH (mode 0755) once the root is writable
(boot-arg rmblob=1). A generated local input, not committed (the probe links hakios-metal).
"""
import sys

out = sys.argv[1]
lines = ['/* Generated by redmagic7/gpu/gen-blob.py: files the kernel writes into the iOS root (rmblob=1). */']
entries = []
for i, spec in enumerate(sys.argv[2:]):
    dest, src = spec.split('=', 1)
    data = open(src, 'rb').read()
    lines.append(f'static const unsigned char rm_blob_{i}[] = {{')
    for start in range(0, len(data), 16):
        lines.append('\t' + ', '.join(f'0x{b:02x}' for b in data[start:start + 16]) + ',')
    lines.append('};')
    entries.append((dest, i, len(data)))
lines.append('static const struct { const char *path; const unsigned char *data; unsigned long length; } rm_blobs[] = {')
for dest, i, n in entries:
    lines.append(f'\t{{ "{dest}", rm_blob_{i}, {n}UL }},')
lines.append('};')
open(out, 'w').write('\n'.join(lines) + '\n')
print(out, ':', ', '.join(f'{d} ({n} bytes)' for d, _, n in entries))
