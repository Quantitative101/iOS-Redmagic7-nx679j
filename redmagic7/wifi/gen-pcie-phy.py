#!/usr/bin/env python3
"""Write umi_pcie_phy.h for the RedMagic 7 from the live device tree's pcie@1c00000 qcom,phy-sequence.

usage: gen-pcie-phy.py LIVE.dts OUT.h
"""
import re
import sys

dts = open(sys.argv[1]).read()
start = dts.index('pcie@1c00000 {')
node = dts[start:start + 20000]
seq = re.search(r'qcom,phy-sequence = <([^>]*)>', node).group(1).split()
vals = [int(x, 16) for x in seq]
assert len(vals) % 3 == 0, len(vals)
with open(sys.argv[2], 'w') as out:
    out.write('/* RedMagic 7 (NX679J) live DT: pcie@1c00000 qcom,phy-sequence (QMP PHY ver 0x68, SM8450 PCIe0).\n'
              ' * Offset, value, delay in us. Generated by redmagic7/wifi/gen-pcie-phy.py. */\n')
    out.write('static const struct { uint32_t offset, value, delay_us; } umi_pcie_phy[] = {\n')
    for i in range(0, len(vals), 3):
        out.write('\t{ 0x%03x, 0x%02x, %u },\n' % (vals[i], vals[i + 1], vals[i + 2]))
    out.write('};\n')
print(len(vals) // 3, 'entries')
