#!/usr/bin/env python3
"""Turn pinfile's extent map of /data/ios/root.img into the kernel's block table.

usage: gen-extents-h.py root.extents OUT.h

Entries are in 4 KiB UFS blocks: (file block, block relative to the userdata partition, count). The userdata
partition's own position (sda12: 512-byte sector 19503424, 467789464 sectors) is recorded so the kernel can refuse
to run if the GPT it reads says otherwise.
"""
import re
import sys

BLK = 4096
PART_FIRST_4K = 19503424 // 8
PART_BLOCKS_4K = 467789464 // 8

rows = []
for line in open(sys.argv[1]):
    m = re.match(r'extent \d+ logical (\d+) physical (\d+) length (\d+)', line)
    if m:
        lo, ph, ln = (int(x) for x in m.groups())
        assert lo % BLK == 0 and ph % BLK == 0 and ln % BLK == 0, line
        rows.append((lo // BLK, ph // BLK, ln // BLK))
rows.sort()
at = 0
for lo, ph, n in rows:
    assert lo == at, 'extents must cover the file without holes'
    assert ph + n <= PART_BLOCKS_4K, 'extent outside userdata'
    at += n
with open(sys.argv[2], 'w') as f:
    f.write('/* generated by redmagic7/tools/gen-extents-h.py from /data/ios/root.img (pinned f2fs file) */\n')
    f.write(f'#define REDMAGIC_PART_FIRST  {PART_FIRST_4K}ULL\n#define REDMAGIC_PART_BLOCKS {PART_BLOCKS_4K}ULL\n')
    f.write(f'#define REDMAGIC_FILE_BLOCKS {at}ULL\n#define REDMAGIC_NEXTENTS {len(rows)}\n')
    f.write('static const uint64_t redmagic_extents[REDMAGIC_NEXTENTS][3] = {\n')
    for lo, ph, n in rows:
        f.write(f'\t{{ {lo}ULL, {ph}ULL, {n}ULL }},\n')
    f.write('};\n')
print(f'{len(rows)} extents, {at} blocks ({at * BLK >> 20} MiB) -> {sys.argv[2]}')
